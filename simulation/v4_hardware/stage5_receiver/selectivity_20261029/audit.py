"""Hash, numerical and generated-netlist audit. Does not launch ngspice.

All reads are local. Intercept execute() after generation to verify exact bytes;
TI source/model copy operations are intercepted to compare existing bytes only.
"""
import json,hashlib,subprocess
from pathlib import Path
import numpy as np
import run_selectivity as sim
import run_baseband as bb
from run_selectivity import HERE,WORK,sha,readraw

class Verified(Exception): pass

def main():
    rows=[json.loads(p.read_text()) for p in sorted((HERE/'results').glob('*.json'))]
    generated=[];files=[];numerical=[]
    def checkfile(p,expected=None):
        assert p.exists(),p
        digest=sha(p)
        if expected is not None:assert digest==expected,str(p)+' hash mismatch'
        files.append(dict(path=str(p.resolve()),sha256=digest,bytes=p.stat().st_size))
    def intercept(name,net,c):
        net=net.replace('@RAW@',(WORK/(name+'.raw')).as_posix())
        assert (HERE/'netlists'/(name+'.cir')).read_bytes()==net.encode('ascii'),name+' regeneration mismatch'
        generated.append(name);raise Verified()
    old_write=Path.write_bytes
    def compare_write(path,data):
        assert path.read_bytes()==data,str(path)+' dependency changed'
        return len(data)
    sim.execute=intercept;bb.execute=intercept;Path.write_bytes=compare_write
    try:
        for r in rows:
            n,c,m=r['name'],r['config'],r['metrics']
            checkfile(HERE/'netlists'/(n+'.cir'),r['net_sha256'])
            checkfile(Path(r['raw_path']),r['raw_sha256'])
            checkfile(HERE/'results'/(n+'.log'),r['log_sha256'])
            log=(HERE/'results'/(n+'.log')).read_text(errors='replace')
            assert 'Error:' not in log and 'timestep too small' not in log,n
            if 'integrated' in m:
                checkfile(HERE/'netlists'/(n+'_source.cir'),m['source_sha256'])
            try:
                if 'g31' in m:sim.ac(n,**c)
                elif 'en31' in m:sim.noise(n,**c)
                elif 'integrated' in m:bb.run(n,integrated=m['integrated'],**c)
                else:sim.tran(n,**c)
            except Verified:pass
            else:raise AssertionError(n+' missing generation check')
    finally:Path.write_bytes=old_write
    # Independent direct Fourier recomputation for the figures' decisive points.
    by={r['name']:r for r in rows}
    for n in ['R1_clean','R1_blk_1p6M_10m','B_clean','B_low_1V','B_blk_29M_10m','B_check_step025']:
        r=by[n];d=readraw(Path(r['raw_path']));a=r['config']['start']*1e-6;b=r['config']['stop']*1e-6
        u=np.linspace(a,b,round((b-a)/.5e-9),endpoint=False);v=np.interp(u,d['time'],d['v(out)'])
        amp=float(np.hypot(2*np.mean(v*np.cos(2*np.pi*20e3*u)),2*np.mean(v*np.sin(2*np.pi*20e3*u))))
        err=abs(amp-r['metrics']['bb_fundamental_peak']);assert err<1e-9,(n,err)
        numerical.append(dict(name=n,fundamental_peak=amp,absolute_difference=err))
    failures=json.loads((HERE/'failures.json').read_text())
    for fail in failures:
        for f in fail['files']:checkfile(Path(f['path']),f['sha256'])
        if fail['status']=='timeout':assert not (WORK/(fail['name']+'.raw')).exists()
    frozen=[(HERE.parents[1]/'AM_20k_31MHz_V4_3_REPAIRED.ms14','99dffd203eb501498e8884ce02005a977b9f295d380ad3c7afea227f26296394'),
        (HERE.parents[1]/'repair_20261011/final_actual.cir','d9aba8eff74e679f709bc6a680bf569e6dab87a00303b6ff138f19d4964ccaaf')]
    for p,h in frozen:checkfile(p,h)
    checkfile(bb.MODEL);checkfile(HERE/'sources/OPAx197.LIB',sha(bb.MODEL));checkfile(sim.EXE)
    for p in sorted(HERE.glob('*.py')):checkfile(p)
    for p in sorted((HERE/'results').glob('*.json')):checkfile(p)
    for name in ['summary.json','measurements.csv','selectivity_blockers.png','baseband_outputs.png','failures.json']:
        checkfile(HERE/name)
    for name in ['S05_R2_candidate.cir','S05_03_选频阻塞与基带验证.md','S05_04_R2接收候选与补购清单.md']:
        checkfile(HERE.parent/name)
    manifest=dict(successful_analyses=len(rows),regenerated_netlists=len(generated),numerical_checks=numerical,
        failures=failures,retained_initialization_counterexamples=['B_bb_sine_v2'],files=files,
        notes=['raw arrays stay on this machine under the existing gitignore policy',
          'all successful cases regenerated byte-for-byte without launching a solver',
          'first-batch 137 results and frozen Multisim sources were not modified'])
    (HERE/'evidence_manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    print(json.dumps(dict(successful_analyses=len(rows),regenerated=len(generated),hashes=len(files),numerical_checks=numerical)))

if __name__=='__main__':main()
